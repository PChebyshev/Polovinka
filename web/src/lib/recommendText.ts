import type { MeResponse } from '@polovinka/shared';
import { plural } from './format';

export interface RecommendVariant {
  key: string;
  label: string;
  text: string;
}

/**
 * Готовые тексты для сообщения друзьям. Без имён — склонять их нельзя надёжно,
 * а друзья и так знают, кто «мы». Ссылка добавляется отдельно в конце.
 */
export function recommendVariants(me: MeResponse): RecommendVariant[] {
  const c = me.counters;
  const days = c.daysTogether;
  const daysText = `${days} ${plural(days, 'день', 'дня', 'дней')}`;
  const pct = c.guessesTotal >= 6 ? Math.round((c.guessesRight / c.guessesTotal) * 100) : null;

  const warm =
    days >= 3
      ? `Мы уже ${daysText} играем в Половинку — это один вопрос в день на двоих. Утром 20 секунд: выбираешь ответ за себя и угадываешь, что выберет половинка. Вечером — раскрытие, и иногда узнаёшь что-то совсем неожиданное. Попробуйте вдвоём, кажется, вам понравится 🙂`
      : `Мы недавно начали играть в Половинку — это один вопрос в день на двоих. Утром 20 секунд: выбираешь ответ за себя и угадываешь, что выберет половинка. Вечером — раскрытие, и иногда узнаёшь что-то совсем неожиданное. Попробуйте вдвоём, кажется, вам понравится 🙂`;

  const short = 'Нашли классную штуку для пар: один вопрос в день, 20 секунд на двоих. Без регистрации и рекламы, работает прямо в браузере. Попробуйте 🙂';

  const fun =
    pct === null
      ? 'Проверяем, насколько хорошо знаем друг друга. Результаты… поучительные 😅 Половинка — один вопрос в день на двоих. Интересно, что узнаете вы.'
      : pct >= 100
        ? 'Пока угадываем друг друга на все 100%, но вопросы становятся всё хитрее 😅 Половинка — один вопрос в день на двоих. Интересно, что узнаете вы.'
        : `Оказалось, мы знаем друг друга на ${pct}%. Остальные ${100 - pct}% выясняем каждый вечер 😅 Половинка — один вопрос в день на двоих. Интересно, что узнаете вы.`;

  const why =
    'Если хочется чуть больше разговоров не про быт — попробуйте Половинку. Один вопрос в день на двоих: «море или горы», «что бы тебя сегодня обрадовало», а вечером сравниваете ответы. У нас из этого часто вырастает разговор на весь вечер.';

  return [
    { key: 'warm', label: 'Тепло', text: warm },
    { key: 'short', label: 'Коротко', text: short },
    { key: 'fun', label: 'С юмором', text: fun },
    { key: 'why', label: 'Зачем это', text: why },
  ];
}
