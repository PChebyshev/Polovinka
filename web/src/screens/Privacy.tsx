import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { api, type AppConfig } from '../lib/api';
import { useStore } from '../lib/store';
import { Card, Label } from '../components/ui';

function List({ items }: { items: string[] }) {
  return (
    <ul className="mt-2 space-y-1.5 text-sm">
      {items.map((t) => (
        <li key={t} className="flex gap-2">
          <span className="text-accent">•</span>
          <span>{t}</span>
        </li>
      ))}
    </ul>
  );
}

/** «Что мы храним»: честный список данных простыми словами. Публичная страница. */
export function Privacy() {
  const { me } = useStore();
  const [cfg, setCfg] = useState<AppConfig | null>(null);
  useEffect(() => {
    api
      .config()
      .then(setCfg)
      .catch(() => undefined);
  }, []);

  return (
    <div className="mx-auto max-w-md px-4 pb-28 pt-6">
      <Link to={me ? '/settings' : '/'} className="text-sm text-muted">
        ← Назад
      </Link>
      <h1 className="mt-3 text-2xl font-bold">Что мы храним</h1>
      <p className="mt-2 text-sm text-muted">
        Половинка — про близость, поэтому данных минимум. Без рекламы, без сторонней аналитики, данные никому не продаём и не передаём.
      </p>

      <Card className="mt-4">
        <Label>Храним</Label>
        <List
          items={[
            'Имя, которое вы ввели, и часовой пояс — чтобы вопросы приходили вовремя.',
            'Ваши ответы, «почему», жесты и письма из капсул — их видите только вы двое.',
            'Почту — только если вы сами её привязали, чтобы вернуть доступ.',
            'Подписку на уведомления — адрес, который выдаёт браузер.',
            'Технические события без содержимого ответов: «ответил», «открыл ссылку» — чтобы понимать, что работает.',
          ]}
        />
      </Card>

      <Card className="mt-3">
        <Label>Не храним и не собираем</Label>
        <List
          items={[
            'Номер телефона, контакты, геолокацию, фото.',
            'Пароли: их просто нет. Коды входа и восстановления хранятся только в виде хеша.',
            'Счётчики и аналитику Google, Яндекса и других компаний: на сайте их нет.',
          ]}
        />
      </Card>

      <Card className="mt-3">
        <Label>Где и кто</Label>
        <List
          items={[
            cfg?.dataLocation
              ? `Сервер находится: ${cfg.dataLocation}.`
              : 'Все данные лежат в одной базе на арендованном сервере. Ни в какие сторонние сервисы мы их не передаём.',
            'Работает без App Store и Google Play, открывается без VPN.',
            'Уведомления доставляют push-сервисы Apple или Google — через них проходит только текст самого уведомления. Письма с кодами входа уходят через почтовый сервис.',
            'Технически доступ к базе есть у владельца сервера. Мы не читаем ответы и не используем их ни для чего, кроме работы приложения.',
            'Ответы других пар показываем только числом, когда ответивших не меньше двадцати, — без имён и без возможности узнать, кто это.',
            ...(cfg?.ai
              ? [
                  `Идеи после ответов, подсказки заботы и «вопрос по вашим ответам» составляет ИИ — ${cfg.ai}. Ему передаются тексты вопросов и ваших ответов, без имён.`,
                ]
              : []),
            ...(cfg?.operator ? [`Оператор персональных данных: ${cfg.operator}.`] : []),
          ]}
        />
      </Card>

      <Card className="mt-3">
        <Label>Ваши права</Label>
        <List
          items={[
            'Скачать всю историю файлом: Настройки → Приватность → «Скачать нашу историю».',
            'Удалить историю пары: Настройки → Приватность → «Удалить нашу историю». Удаляется у обоих и безвозвратно.',
            'Отвязать почту и выйти на всех устройствах: Настройки → Доступ и восстановление.',
            ...(cfg?.contact ? [`Вопросы о данных: ${cfg.contact}.`] : []),
          ]}
        />
      </Card>
    </div>
  );
}
