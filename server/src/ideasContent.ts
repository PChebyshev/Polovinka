const GENERIC: { same: Pair; diff: Pair } = {
  same: ['Раз совпали — сделайте это вместе на неделе.', 'Почему вы оба выбрали это?'],
  diff: ['Попробуйте по очереди: сначала по-твоему, потом по-моему.', 'Спросите, почему именно так, — это и есть открытие.'],
};

export function curatedIdeas(category: string, same: boolean): RoundIdea[] {
  const set = IDEAS[category] ?? GENERIC;
  const [doText, talkText] = same ? set.same : set.diff;
  return [
    { kind: 'do', text: doText },
    { kind: 'talk', text: talkText },
  ];
}
